'use client';

import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Loader2 } from 'lucide-react';
import { toast } from 'sonner';
import { PageHeader } from '@/components/app/shared';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Input, Label, NativeSelect, Textarea } from '@/components/ui/input';
import { useApi, useToken } from '@/lib/api';

interface ProfileResponse {
  profile: { headline: string | null; location: string | null; summary: string | null; skills: string[]; totalYearsExp: number } | null;
  preferences: {
    titles: string[]; locations: string[]; remoteOnly: boolean; includeInternational: boolean; needsVisaSponsorship: boolean;
    minMatchScore: number; autoGenerateDocs: boolean; digestFrequency: 'DAILY' | 'WEEKLY' | 'OFF';
  } | null;
}

const list = (v: FormDataEntryValue | null) => String(v ?? '').split(',').map((s) => s.trim()).filter(Boolean);

export default function SettingsPage() {
  const api = useApi();
  const { ready } = useToken();
  const qc = useQueryClient();
  const { data } = useQuery({ queryKey: ['profile'], queryFn: () => api<ProfileResponse>('/profile'), enabled: ready });

  const savePrefs = useMutation({
    mutationFn: (body: Record<string, unknown>) => api('/profile/preferences', { method: 'PATCH', body: JSON.stringify(body) }),
    onSuccess: () => (qc.invalidateQueries({ queryKey: ['profile'] }), toast.success('Preferences saved')),
    onError: (e) => toast.error((e as Error).message),
  });
  const saveProfile = useMutation({
    mutationFn: (body: Record<string, unknown>) => api('/profile', { method: 'PATCH', body: JSON.stringify(body) }),
    onSuccess: () => (qc.invalidateQueries({ queryKey: ['profile'] }), toast.success('Profile saved')),
    onError: (e) => toast.error((e as Error).message),
  });

  if (!data) return null;
  const p = data.preferences;
  const prof = data.profile;

  return (
    <>
      <PageHeader title="Settings" description="Tell the copilot what you are looking for." />
      <div className="grid gap-6 lg:grid-cols-2">
        <Card>
          <CardHeader>
            <CardTitle>Job search preferences</CardTitle>
            <CardDescription>Used for scheduled searches, scoring and notifications.</CardDescription>
          </CardHeader>
          <CardContent>
            <form
              className="space-y-4"
              onSubmit={(e) => {
                e.preventDefault();
                const f = new FormData(e.currentTarget);
                savePrefs.mutate({
                  titles: list(f.get('titles')),
                  locations: list(f.get('locations')),
                  remoteOnly: f.get('remoteOnly') === 'on',
                  includeInternational: f.get('includeInternational') === 'on',
                  needsVisaSponsorship: f.get('needsVisaSponsorship') === 'on',
                  autoGenerateDocs: f.get('autoGenerateDocs') === 'on',
                  minMatchScore: Number(f.get('minMatchScore')),
                  digestFrequency: f.get('digestFrequency'),
                });
              }}
            >
              <div className="space-y-1">
                <Label htmlFor="titles">Target roles (comma separated, max 5)</Label>
                <Input id="titles" name="titles" defaultValue={p?.titles.join(', ')} placeholder="Full Stack Developer, React Developer" />
              </div>
              <div className="space-y-1">
                <Label htmlFor="locations">Preferred locations</Label>
                <Input id="locations" name="locations" defaultValue={p?.locations.join(', ')} placeholder="Bengaluru, Hyderabad, Pune" />
              </div>
              <div className="grid grid-cols-2 gap-4">
                <div className="space-y-1">
                  <Label htmlFor="minMatchScore">Notify me above score</Label>
                  <Input id="minMatchScore" name="minMatchScore" type="number" min={0} max={100} defaultValue={p?.minMatchScore ?? 60} />
                </div>
                <div className="space-y-1">
                  <Label htmlFor="digestFrequency">Job digest</Label>
                  <NativeSelect id="digestFrequency" name="digestFrequency" defaultValue={p?.digestFrequency ?? 'DAILY'}>
                    <option value="DAILY">Daily</option>
                    <option value="WEEKLY">Weekly</option>
                    <option value="OFF">Off</option>
                  </NativeSelect>
                </div>
              </div>
              {[
                ['remoteOnly', 'Remote jobs only', p?.remoteOnly],
                ['includeInternational', 'Include international jobs', p?.includeInternational],
                ['needsVisaSponsorship', 'I need visa sponsorship', p?.needsVisaSponsorship],
                ['autoGenerateDocs', 'Auto-draft tailored resume + cover letter for strong matches', p?.autoGenerateDocs ?? true],
              ].map(([name, label, checked]) => (
                <label key={name as string} className="flex items-center gap-2 text-sm">
                  <input type="checkbox" name={name as string} defaultChecked={!!checked} className="h-4 w-4 accent-[hsl(var(--primary))]" />
                  {label}
                </label>
              ))}
              <Button type="submit" disabled={savePrefs.isPending}>
                {savePrefs.isPending && <Loader2 className="animate-spin" />} Save preferences
              </Button>
            </form>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Candidate profile</CardTitle>
            <CardDescription>
              Built from your resume ({prof?.totalYearsExp ?? 0} yrs experience). Only add skills you genuinely have; tailored resumes never go beyond this list.
            </CardDescription>
          </CardHeader>
          <CardContent>
            <form
              className="space-y-4"
              onSubmit={(e) => {
                e.preventDefault();
                const f = new FormData(e.currentTarget);
                saveProfile.mutate({
                  headline: String(f.get('headline') ?? ''),
                  location: String(f.get('location') ?? ''),
                  summary: String(f.get('summary') ?? ''),
                  skills: list(f.get('skills')),
                });
              }}
            >
              <div className="space-y-1">
                <Label htmlFor="headline">Headline</Label>
                <Input id="headline" name="headline" defaultValue={prof?.headline ?? ''} />
              </div>
              <div className="space-y-1">
                <Label htmlFor="location">Location</Label>
                <Input id="location" name="location" defaultValue={prof?.location ?? ''} />
              </div>
              <div className="space-y-1">
                <Label htmlFor="summary">Summary</Label>
                <Textarea id="summary" name="summary" rows={4} defaultValue={prof?.summary ?? ''} />
              </div>
              <div className="space-y-1">
                <Label htmlFor="skills">Skills (comma separated)</Label>
                <Textarea id="skills" name="skills" rows={4} defaultValue={prof?.skills.join(', ')} />
              </div>
              <Button type="submit" disabled={saveProfile.isPending || !prof}>
                {saveProfile.isPending && <Loader2 className="animate-spin" />} Save profile
              </Button>
            </form>
          </CardContent>
        </Card>
      </div>
    </>
  );
}
