async function generate(s: State, type: string, jobId: string, extra: { tone?: string; recruiterName?: string }) {
  const r = activeResume(s);
  if (!r) throw new LocalError(400, 'Upload your resume first.');
  const { job, detail } = await findJob(s, jobId);
  const jd: JdAnalysis = {
    ...analyzeJdHeuristic(detail?.description ?? '', job.title),
    ...(detail
      ? {
          requiredSkills: detail.analysis.requiredSkills,
          preferredSkills: detail.analysis.preferredSkills,
          atsKeywords: detail.analysis.atsKeywords,
          minYearsExperience: detail.analysis.minYears,
          maxYearsExperience: detail.analysis.maxYears,
        }
      : {}),
  };
  const lite = { title: job.title, companyName: job.company };
  const description = detail?.description ?? '';
  const useAi = !!getAiKey();
  const parsed = { ...r.parsed, skills: s.profile?.skills ?? r.parsed.skills };
  let model = 'built-in';
  const tryAi = async <T,>(fn: () => Promise<T>, fallback: () => T): Promise<T> => {
    if (!useAi) return fallback();
    try {
      const out = await fn();
      model = 'gemini';
      return out;
    } catch (e) {
      model = `built-in (AI failed: ${(e as Error).message.slice(0, 80)})`;
      return fallback();
    }
  };
  const version = s.documents.filter((d) => d.jobId === jobId && d.type === type).length + 1;
  const base = { id: uid('d'), type, jobId, version, atsScoreBefore: null as number | null, atsScoreAfter: null as number | null, guardrailFlags: [] as string[], createdAt: iso() };

  if (type === 'TAILORED_RESUME') {
    const have = new Set(parsed.skills.map(skillKey));
    const missing = [...jd.requiredSkills, ...jd.preferredSkills].filter((k) => !have.has(skillKey(k)));
    const { resume, flags } = await tryAi(
      async () => enforceHonesty(parsed, r.rawText, await geminiJson(TailoredResumeSchema, prompts.tailorResume(parsed, jd, description, missing))),
      () => templates.tailorResume(parsed, r.rawText, jd),
    );
    const before = atsKeywordCoverage(r.rawText, jd.atsKeywords);
    const after = atsKeywordCoverage(tailoredToText(resume), jd.atsKeywords);
    return { ...base, content: { ...resume, missingSkills: missing }, atsScoreBefore: Math.round(before.ratio * 100), atsScoreAfter: Math.round(after.ratio * 100), guardrailFlags: flags, model };
  }
  if (type === 'COVER_LETTER') {
    const content = await tryAi(
      () => geminiJson(CoverLetterSchema, prompts.coverLetter(parsed, job.title, job.company, description, extra.tone ?? 'confident and warm')),
      () => templates.coverLetter(parsed, lite, jd),
    );
    return { ...base, content, model };
  }
  if (type === 'RECRUITER_EMAIL') {
    const content = await tryAi(() => geminiJson(OutreachSchema, prompts.outreach(parsed, job.title, job.company, extra.recruiterName)), () => templates.outreach(parsed, lite));
    content.linkedinConnectionNote = content.linkedinConnectionNote.slice(0, 300);
    return { ...base, content, model };
  }
  const content = await tryAi(() => geminiJson(InterviewPrepSchema, prompts.interviewPrep(parsed, jd, job.title, job.company)), () => templates.interviewPrep(parsed, lite, jd));
  return { ...base, content, model };
}

function wordDoc(title: string, bodyHtml: string): { url: string } {
  const html = `<html><head><meta charset="utf-8"><title>${title}</title></head><body style="font-family:Calibri,Arial;font-size:11pt">${bodyHtml}</body></html>`;
  return { url: URL.createObjectURL(new Blob([html], { type: 'application/msword' })) };
}
const esc = (t: string) => String(t ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function resumeHtml(c: any, p: ParsedResume) {
  return `<h1 style="text-align:center;margin:0">${esc(p.fullName ?? '')}</h1>
<p style="text-align:center">${esc([p.email, p.phone, p.location, ...p.links].filter(Boolean).join(' | '))}</p>
<p style="text-align:center"><i>${esc(c.headline)}</i></p>
<h3>SUMMARY</h3><p>${esc(c.summary)}</p>
<h3>SKILLS</h3><p>${esc(c.skills.join(' • '))}</p>
<h3>EXPERIENCE</h3>${c.experience
    .map((e: any) => `<p><b>${esc(e.title)}, ${esc(e.company)}</b> (${esc(e.startDate ?? '')} – ${e.current ? 'Present' : esc(e.endDate ?? '')})</p><ul>${e.bullets.map((b: string) => `<li>${esc(b)}</li>`).join('')}</ul>`)
    .join('')}
${c.projects?.length ? `<h3>PROJECTS</h3>${c.projects.map((x: any) => `<p><b>${esc(x.name)}</b>: ${esc(x.description)}</p>`).join('')}` : ''}
${c.education?.length ? `<h3>EDUCATION</h3>${c.education.map((e: any) => `<p>${esc([e.degree, e.field].filter(Boolean).join(', '))} — ${esc(e.institution)}</p>`).join('')}` : ''}
${c.certifications?.length ? `<h3>CERTIFICATIONS</h3>${c.certifications.map((x: any) => `<p>${esc(x.name)}</p>`).join('')}` : ''}`;
}

