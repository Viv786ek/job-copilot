export async function localRequest<T>(path: string, init: RequestInit = {}): Promise<T> {
  const method = (init.method ?? 'GET').toUpperCase();
  const url = new URL(path, 'http://local');
  const p = url.pathname.split('/').filter(Boolean);
  const q = url.searchParams;
  const body = typeof init.body === 'string' ? JSON.parse(init.body) : {};
  const s = load();
  const done = <R,>(v: R, persist = method !== 'GET') => {
    if (persist) save(s);
    return v as unknown as T;
  };
  const c = candidate(s);

  // ---------------- career insights
  if (p[0] === 'insights') {
    if (!c) throw new LocalError(400, 'Upload your resume first: insights are computed against your profile.');
    const countries = (q.get('countries') ?? s.preferences.countries.join(',')).split(',').filter(Boolean);
    const regions = regionsCovering(countries);
    const jobs = (await allJobs(s)).filter(
      (j) => !countries.length || j.countries.some((x) => countries.includes(x)) || j.remoteScope === 'GLOBAL' || (j.remoteScope === 'REGION' && j.regions.some((r) => regions.includes(r))),
    );
    const { meta } = await loadIndex();
    return done(
      {
        ...computeCareerInsights(jobs.map((j) => ({ ...j, score: score(c, j).score })), c.skills),
        countriesFilter: countries,
        datasetGeneratedAt: meta.generatedAt,
      },
      false,
    );
  }

  // ---------------- dashboard
  if (p[0] === 'dashboard') {
    const pipeline: Record<string, number> = {};
    for (const a of s.applications) pipeline[a.status] = (pipeline[a.status] ?? 0) + 1;
    const applied = s.applications.filter((a) => a.status !== 'DRAFT').length;
    const responded = s.applications.filter((a) => RESPONDED.includes(a.status)).length;
    const tailored = s.documents.filter((d) => d.type === 'TAILORED_RESUME' && d.atsScoreBefore != null);
    const avg = (xs: number[]) => (xs.length ? Math.round(xs.reduce((a, b) => a + b, 0) / xs.length) : 0);
    let top: MatchResult[] = [];
    let strong = 0;
    if (c) {
      const all = (await allJobs(s)).filter((j) => !s.flags[j.id]?.dismissed).map((j) => score(c, j));
      strong = all.filter((m) => m.score >= 75).length;
      top = all.sort((a, b) => b.score - a.score).slice(0, 200);
    }
    const missing = new Map<string, number>();
    for (const m of top.slice(0, 100)) for (const k of m.missingRequiredSkills) missing.set(k, (missing.get(k) ?? 0) + 1);
    const weeks = new Map<string, { applied: number; responses: number }>();
    for (const a of s.applications.filter((x) => x.appliedAt)) {
      const d = new Date(a.appliedAt!);
      d.setDate(d.getDate() - ((d.getDay() + 6) % 7));
      const k = d.toISOString().slice(0, 10);
      const w = weeks.get(k) ?? { applied: 0, responses: 0 };
      w.applied++;
      if (RESPONDED.includes(a.status)) w.responses++;
      weeks.set(k, w);
    }
    const interviews = s.applications.flatMap((a) => a.interviews);
    const r = activeResume(s);
    return done(
      {
        resumeHealth: r?.health.score ?? 0,
        avgMatchScore: avg(top.slice(0, 50).map((m) => m.score)),
        topMatches: strong,
        atsImprovement: { avgBefore: avg(tailored.map((d) => d.atsScoreBefore!)), avgAfter: avg(tailored.map((d) => d.atsScoreAfter!)), delta: avg(tailored.map((d) => d.atsScoreAfter!)) - avg(tailored.map((d) => d.atsScoreBefore!)), documents: tailored.length },
        pipeline,
        applied,
        interviews: interviews.length,
        upcomingInterviews: interviews.filter((i) => new Date(i.scheduledAt) > new Date()).length,
        rejections: pipeline.REJECTED ?? 0,
        offers: (pipeline.OFFER ?? 0) + (pipeline.ACCEPTED ?? 0),
        responseRate: applied ? Math.round((responded / applied) * 100) : 0,
        followUpsDue: s.applications.filter((a) => a.followUpAt && new Date(a.followUpAt) <= new Date() && !a.responded && ['APPLIED', 'SCREENING'].includes(a.status)).length,
        weekly: [...weeks.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([week, v]) => ({ week, ...v })),
        topMissingSkills: [...missing.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([skill, count]) => ({ skill, count })),
        hasResume: !!r,
      },
      false,
    );
  }

  // ---------------- profile
  if (p[0] === 'profile') {
    if (method === 'GET') {
      const r = activeResume(s);
      return done(
        {
          profile: s.profile ? { ...s.profile, totalYearsExp: r ? computeYearsOfExperience(r.parsed) : 0 } : null,
          preferences: s.preferences,
        },
        false,
      );
    }
    if (p[1] === 'preferences') Object.assign(s.preferences, body);
    else if (s.profile) {
      Object.assign(s.profile, {
        headline: body.headline ?? s.profile.headline,
        location: body.location ?? s.profile.location,
        summary: body.summary ?? s.profile.summary,
        skills: body.skills ? normalizeSkills(body.skills) : s.profile.skills,
      });
    } else throw new LocalError(400, 'Upload your resume first.');
    return done({ ok: true });
  }

  // ---------------- resumes
  if (p[0] === 'resumes') {
    const view = (r: StoredResume) => ({ id: r.id, fileName: r.fileName, createdAt: r.createdAt, status: 'PARSED', healthScore: r.health.score, errorMessage: null, parser: r.parser, active: r.id === (activeResume(s)?.id ?? null) });
    if (method === 'GET' && !p[1]) return done(s.resumes.map(view), false);
    if (method === 'POST' && !p[1]) {
      const file = init.body instanceof FormData ? (init.body.get('file') as File | null) : null;
      if (!file) throw new LocalError(400, 'No file selected');
      const rawText = await extractResumeText(file);
      const r = await ingestProfileText(s, rawText, file.name, isLinkedInExport(rawText) ? 'linkedin-pdf' : 'resume');
      return done(view(r));
    }
    // Pasted profile text (LinkedIn "About"/"Experience", a portfolio, or any resume text).
    if (method === 'POST' && p[1] === 'text') {
      const text = String(body.text ?? '').replace(/\r/g, '').trim();
      if (text.length < 150) throw new LocalError(400, 'Paste at least a few paragraphs: your headline, experience and skills.');
      if (text.length > 60_000) throw new LocalError(400, 'That is longer than a resume; paste only your profile sections.');
      const origin: StoredResume['origin'] = body.source === 'linkedin' || isLinkedInExport(text) ? 'linkedin-text' : 'pasted';
      const r = await ingestProfileText(s, text, origin === 'pasted' ? 'Pasted profile' : 'LinkedIn profile (pasted)', origin);
      if (typeof body.linkedinUrl === 'string' && /linkedin\.com\/in\//i.test(body.linkedinUrl) && !r.parsed.links.some((l) => /linkedin/i.test(l))) {
        r.parsed.links.unshift(body.linkedinUrl.trim());
      }
      return done(view(r));
    }
    const r = s.resumes.find((x) => x.id === p[1]);
    if (!r) throw new LocalError(404, 'Resume not found');
    if (method === 'DELETE') {
      s.resumes = s.resumes.filter((x) => x.id !== r.id);
      if (s.activeResumeId === r.id) {
        s.activeResumeId = s.resumes[0]?.id ?? null;
        if (!s.resumes.length) s.profile = null;
      }
      return done(undefined);
    }
    if (p[2] === 'download') return done(wordDoc(r.fileName, `<pre style="white-space:pre-wrap">${esc(r.rawText)}</pre>`), false);
    if (p[2] === 'activate' || p[2] === 'reparse') {
      s.activeResumeId = r.id;
      if (p[2] === 'reparse') {
        r.parsed = parseResumeText(r.rawText);
        r.health = scoreResumeHealth(r.parsed, r.rawText);
      }
      s.profile = { headline: r.parsed.headline ?? null, location: r.parsed.location ?? null, summary: r.parsed.summary ?? null, skills: r.parsed.skills };
      return done({ ok: true });
    }
    return done({ ...view(r), parsed: r.parsed, healthReport: r.health, rawText: r.rawText }, false);
  }

  // ---------------- jobs
  if (p[0] === 'jobs') {
    if (p[1] === 'countries') {
      const { meta } = await loadIndex();
      return done({ withJobs: meta.countries, all: listCountries() }, false);
    }
    if (p[1] === 'sources') {
      const { meta } = await loadIndex();
      return done({ generatedAt: meta.generatedAt, totalJobs: meta.totalJobs, companies: meta.companies, sources: meta.sources, sponsorRegisters: meta.sponsorRegisters }, false);
    }
    if (p[1] === 'feed') {
      const page = Math.max(1, Number(q.get('page') ?? 1));
      const pageSize = Math.min(50, Number(q.get('pageSize') ?? 20));
      const countries = (q.get('countries') ?? '').split(',').filter(Boolean);
      const includeRemote = q.get('includeRemote') !== 'false';
      const regions = regionsCovering(countries);
      const workModes = (q.get('workModes') ?? '').split(',').filter(Boolean);
      const visa = q.get('visa');
      const days = Number(q.get('postedWithinDays') ?? 0);
      const term = (q.get('q') ?? '').toLowerCase().trim();
      const source = q.get('source');
      const minScore = Number(q.get('minScore') ?? 0);
      const sort = q.get('sort') ?? (c ? 'score' : 'recent');
      const cutoff = days ? Date.now() - days * DAY : 0;
      const level = q.get('level');
      const salaryFloor = Number(q.get('salaryMin') ?? 0);
      const salaryCurrency = q.get('salaryCurrency');
      const salaryListed = q.get('salaryListed') === 'true' || !!salaryFloor;
      const newDays = Number(q.get('newWithinDays') ?? 0);
      const newCutoff = newDays ? Date.now() - newDays * DAY : 0;

      const rows = (await allJobs(s)).filter((j) => {
        const f = s.flags[j.id];
        if (f?.dismissed) return false;
        if (q.get('saved') === 'true' && !f?.saved) return false;
        if (countries.length) {
          const here = j.countries.some((x) => countries.includes(x));
          const remoteOk = includeRemote && (j.remoteScope === 'GLOBAL' || (j.remoteScope === 'REGION' && j.regions.some((r) => regions.includes(r))));
          if (!here && !remoteOk) return false;
        }
        if (q.get('remote') === 'true' && j.workMode !== 'REMOTE') return false;
        if (workModes.length && !workModes.includes(j.workMode ?? '')) return false;
        if (visa === 'sponsors' && j.visaStatus !== 'SPONSORS') return false;
        if (visa === 'likely' && j.visaStatus !== 'SPONSORS' && j.visaStatus !== 'LIKELY') return false;
        if (visa === 'exclude-no' && j.visaStatus === 'NO_SPONSORSHIP') return false;
        if (q.get('relocation') === 'true' && !j.relocation) return false;
        if (source && j.source !== source) return false;
        if (cutoff && j.postedAt && Date.parse(j.postedAt) < cutoff) return false;
        if (newCutoff && (!j.firstSeenAt || Date.parse(j.firstSeenAt) < newCutoff)) return false;
        if (level && LEVELS[level] && !LEVELS[level](j.minYears, j.title)) return false;
        if (salaryListed && j.salaryMin == null && j.salaryMax == null) return false;
        if (salaryFloor && (j.salaryCurrency !== salaryCurrency || (j.salaryMax ?? j.salaryMin ?? 0) < salaryFloor)) return false;
        if (term && !j.title.toLowerCase().includes(term) && !j.company.toLowerCase().includes(term)) return false;
        return true;
      });
      let scored = rows.map((j) => ({ j, m: c ? score(c, j) : null }));
      if (c && minScore) scored = scored.filter((x) => x.m!.score >= minScore);
      scored.sort((a, b) => (sort === 'score' && c ? b.m!.score - a.m!.score : 0) || (b.j.postedAt ?? b.j.firstSeenAt ?? '').localeCompare(a.j.postedAt ?? a.j.firstSeenAt ?? ''));
      return done(
        {
          items: scored.slice((page - 1) * pageSize, page * pageSize).map(({ j, m }) => matchRow(j, m, s, c)),
          total: scored.length,
          page,
          pageSize,
          hasProfile: !!c,
        },
        false,
      );
    }
    if (p[1] === 'import') {
      if (!body.description || body.description.length < 100) {
        throw new LocalError(400, 'Paste the full job description (100+ characters). Browsers cannot fetch other sites directly.');
      }
      const analysis = analyzeJdHeuristic(body.description, body.title);
      const visa = assessVisa(`${body.title ?? ''}\n${body.description}`);
      const id = `imp${uid('').replace(/-/g, '')}`.slice(0, 16);
      const loc = parseLocation(body.location ?? null, analysis.workMode === 'REMOTE' ? 'Remote' : null);
      const job: ImportedJob = {
        id,
        title: body.title || 'Imported role',
        company: body.company || 'Imported company',
        location: body.location ?? '',
        countries: loc.countries,
        regions: loc.regions,
        remoteScope: loc.remoteScope,
        workMode: loc.remote ? 'REMOTE' : loc.hybrid ? 'HYBRID' : analysis.workMode ?? (loc.countries.length ? 'ONSITE' : null),
        visaStatus: visa.status,
        visaConfidence: visa.confidence,
        requiredSkills: analysis.requiredSkills,
        preferredSkills: analysis.preferredSkills,
        postedAt: iso(),
        source: 'MANUAL',
        url: body.url || '',
        relocation: visa.relocation,
        minYears: analysis.minYearsExperience ?? null,
        salaryMin: null,
        salaryMax: null,
        salaryCurrency: null,
        firstSeenAt: iso(),
        alsoOnCount: 0,
        detail: {
          description: body.description,
          applyUrl: body.url || null,
          department: null,
          employmentType: null,
          salary: null,
          visa: { types: visa.visaTypes, evidence: visa.evidence, register: null, requiresAuthorizationIn: visa.requiresAuthorizationIn },
          analysis: { requiredSkills: analysis.requiredSkills, preferredSkills: analysis.preferredSkills, atsKeywords: analysis.atsKeywords, seniority: analysis.seniority, minYears: analysis.minYearsExperience ?? null, maxYears: analysis.maxYearsExperience ?? null },
          ats: null,
        },
      };
      s.imported.unshift(job);
      return done({ jobId: id, match: c ? score(c, job, job.detail) : null });
    }
    if (p[1] === 'analyze') {
      if (!body.description || body.description.length < 100) throw new LocalError(400, 'Paste at least 100 characters of the job description');
      let analysis = analyzeJdHeuristic(body.description, body.title);
      if (getAiKey()) {
        try {
          analysis = await geminiJson(JdAnalysisSchema, prompts.analyzeJd(body.description, body.title, body.company));
          analysis = { ...analysis, requiredSkills: normalizeSkills(analysis.requiredSkills), preferredSkills: normalizeSkills(analysis.preferredSkills) };
        } catch {
          /* keep heuristic analysis */
        }
      }
      const visa = assessVisa(`${body.title ?? ''}\n${body.description}`);
      const match = c
        ? computeMatch(c, {
            title: body.title ?? '', requiredSkills: analysis.requiredSkills, preferredSkills: analysis.preferredSkills, atsKeywords: analysis.atsKeywords,
            minYears: analysis.minYearsExperience ?? null, maxYears: analysis.maxYearsExperience ?? null, embedding: [], location: null,
            workMode: analysis.workMode ?? null, visaSponsorship: null, country: null, visaStatus: visa.status,
          })
        : null;
      if (!match) throw new LocalError(400, 'Upload your resume first so the JD can be matched against it.');
      return done({ analysis, match, visa }, false);
    }
    if (p[1] === 'search') {
      const { meta } = await loadIndex();
      return done({ queued: false, message: `The job index refreshes automatically every 6 hours (last update ${new Date(meta.generatedAt).toLocaleString()}).` }, false);
    }
    if (p[1] === 'career-pages') throw new LocalError(400, 'Adding company career pages runs on the server edition. Paste individual job descriptions here instead.');

    const { job, detail } = await findJob(s, p[1]);
    if (method === 'PATCH') {
      s.flags[job.id] = { ...s.flags[job.id], ...body };
      return done({ ok: true });
    }
    const m = c ? score(c, job, detail) : null;
    const { jobs } = await loadIndex();
    const same = jobs.filter((x) => x.company.toLowerCase() === job.company.toLowerCase());
    const since30 = Date.now() - 30 * DAY;
    const ageDays = job.postedAt ? Math.floor((Date.now() - Date.parse(job.postedAt)) / DAY) : null;
    const recent = same.filter((x) => x.postedAt && Date.parse(x.postedAt) >= since30).length;
    return done(
      {
        job: {
          ...summary(job),
          description: detail?.description ?? '',
          analysis: detail
            ? { title: job.title, seniority: detail.analysis.seniority, requiredSkills: detail.analysis.requiredSkills, preferredSkills: detail.analysis.preferredSkills, atsKeywords: detail.analysis.atsKeywords, minYearsExperience: detail.analysis.minYears, maxYearsExperience: detail.analysis.maxYears, keywords: [], responsibilities: [], educationRequirements: [] }
            : null,
          applyUrl: detail?.applyUrl ?? job.url,
          employmentType: detail?.employmentType ?? null,
          department: detail?.department ?? null,
          salaryMin: detail?.salary?.min ?? null,
          salaryMax: detail?.salary?.max ?? null,
          salaryCurrency: detail?.salary?.currency ?? null,
          visaTypes: detail?.visa.types ?? [],
          visaEvidence: detail?.visa.evidence ?? [],
          sponsorRegister: detail?.visa.register ?? null,
          requiresAuthorizationIn: detail?.visa.requiresAuthorizationIn ?? [],
          ats: detail?.ats ?? null,
          alsoOn: detail?.alsoOn ?? [],
          firstSeenAt: job.firstSeenAt,
        },
        match: m ? { ...m, missingSkills: [...m.missingRequiredSkills, ...m.missingPreferredSkills] } : null,
        documents: s.documents.filter((d) => d.jobId === job.id).map(({ id, type, version }) => ({ id, type, version })),
        insights: {
          openRoles: same.length,
          postedLast30Days: recent,
          sponsoringRoles: same.filter((x) => x.visaStatus === 'SPONSORS' || x.visaStatus === 'LIKELY').length,
          hiringCountries: [...new Set(same.flatMap((x) => x.countries))].slice(0, 20).map((code) => ({ code, name: countryName(code) })),
          sponsorRegister: detail?.visa.register ?? null,
          ats: detail?.ats ?? null,
          postingAgeDays: ageDays,
          tips: [
            ageDays != null && ageDays <= 7 ? 'Fresh posting: applying in the first week noticeably improves response rates.' : null,
            ageDays != null && ageDays > 30 ? 'Posted over a month ago; it may be close to filled. Reach out to a recruiter directly.' : null,
            recent >= 5 ? `${job.company} posted ${recent} roles in the last 30 days: an actively growing team.` : null,
            detail?.visa.register ? `${job.company} holds an active sponsor licence (${detail.visa.register}).` : null,
          ].filter(Boolean),
        },
      },
      false,
    );
  }

  // ---------------- documents
  if (p[0] === 'documents') {
    if (p[1] === 'apply-kit') {
      const r = activeResume(s);
      if (!r) throw new LocalError(400, 'Upload your resume first.');
      const { job, detail } = await findJob(s, p[2]);
      const parsed = r.parsed;
      const [firstName, ...rest] = (parsed.fullName ?? '').trim().split(/\s+/);
      const link = (re: RegExp) => parsed.links.find((l) => re.test(l)) ?? null;
      const authorized = s.preferences.authorizedCountries;
      const authorizedHere = job.countries.length ? job.countries.some((x) => authorized.includes(x)) : null;
      const docs = s.documents.filter((d) => d.jobId === job.id);
      const letter = docs.find((d) => d.type === 'COVER_LETTER');
      return done(
        {
          job: { id: job.id, title: job.title, company: job.company, applyUrl: detail?.applyUrl ?? job.url, ats: detail?.ats ?? null },
          fields: {
            firstName: firstName ?? '',
            lastName: rest.join(' '),
            fullName: parsed.fullName ?? '',
            email: parsed.email ?? '',
            phone: parsed.phone ?? '',
            location: parsed.location ?? '',
            linkedin: link(/linkedin\.com/i),
            github: link(/github\.com/i),
            website: parsed.links.find((l) => !/linkedin|github/i.test(l)) ?? null,
            currentTitle: parsed.experience[0]?.title ?? parsed.headline ?? '',
            currentCompany: parsed.experience[0]?.company ?? '',
            yearsOfExperience: computeYearsOfExperience(parsed),
            authorizedToWork: authorizedHere,
            requiresSponsorship: authorizedHere === null ? null : !authorizedHere,
            willingToRelocate: s.preferences.openToRelocation,
          },
          answers: {
            whyThisCompany: `I'm drawn to ${job.company} because the ${job.title} role lines up with what I do best: ${(s.profile?.skills ?? []).slice(0, 4).join(', ')}.`,
            sponsorshipStatement:
              authorizedHere === false
                ? `I will require visa sponsorship to work in ${job.countries.map(countryName).join(', ')}.${job.visaStatus === 'SPONSORS' ? ' The posting indicates sponsorship is available.' : ''}`
                : authorizedHere
                  ? 'I am authorized to work in this country and do not require sponsorship.'
                  : null,
          },
          documents: {
            tailoredResumeId: docs.find((d) => d.type === 'TAILORED_RESUME')?.id ?? null,
            coverLetterId: letter?.id ?? null,
            coverLetterText: letter?.content?.body ?? null,
          },
        },
        false,
      );
    }
    if (method === 'POST') {
      const type = { 'tailored-resume': 'TAILORED_RESUME', 'cover-letter': 'COVER_LETTER', outreach: 'RECRUITER_EMAIL', 'interview-prep': 'INTERVIEW_PREP' }[p[1] as string];
      if (!type) throw new LocalError(404, 'Unknown document type');
      const doc = await generate(s, type, body.jobId, body);
      s.documents.unshift(doc);
      return done(await withJob(s, doc));
    }
    if (method === 'GET' && !p[1]) {
      const type = q.get('type');
      return done(await Promise.all(s.documents.filter((d) => !type || d.type === type).map((d) => withJob(s, d))), false);
    }
    const doc = s.documents.find((d) => d.id === p[1]);
    if (!doc) throw new LocalError(404, 'Document not found');
    if (p[2] === 'docx') {
      const r = activeResume(s);
      return done(
        doc.type === 'TAILORED_RESUME' && r
          ? wordDoc('Tailored resume', resumeHtml(doc.content, r.parsed))
          : wordDoc('Cover letter', String(doc.content.body ?? '').split('\n').map((l: string) => `<p>${esc(l)}</p>`).join('')),
        false,
      );
    }
    if (method === 'PATCH') {
      doc.content = body.content;
      return done(await withJob(s, doc));
    }
    return done(await withJob(s, doc), false);
  }

  // ---------------- applications
  if (p[0] === 'applications') {
    if (p[1] === 'interviews') return done(s.applications.flatMap((a) => a.interviews.map((i) => ({ ...i, application: { id: a.id, company: a.company, role: a.role } }))), false);
    if (method === 'GET' && !p[1]) {
      const status = q.get('status');
      const term = (q.get('q') ?? '').toLowerCase();
      return done(
        s.applications
          .filter((a) => (!status || a.status === status) && (!term || a.company.toLowerCase().includes(term) || a.role.toLowerCase().includes(term)))
          .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)),
        false,
      );
    }
    if (method === 'POST' && !p[1]) {
      const status = body.status ?? 'DRAFT';
      const appliedAt = body.appliedAt ? new Date(body.appliedAt).toISOString() : status !== 'DRAFT' ? iso() : null;
      let matchScore: number | null = null;
      if (body.jobId && c) {
        try {
          const { job, detail } = await findJob(s, body.jobId);
          matchScore = score(c, job, detail).score;
        } catch {
          /* job gone from index */
        }
      }
      const a: App = {
        id: uid('a'), jobId: body.jobId ?? null, company: body.company, role: body.role, source: body.source, jobUrl: body.jobUrl ?? null,
        status, appliedAt, followUpAt: body.followUpAt ? new Date(body.followUpAt).toISOString() : appliedAt ? new Date(Date.parse(appliedAt) + 7 * DAY).toISOString() : null,
        recruiterName: body.recruiterName ?? null, recruiterEmail: body.recruiterEmail ?? null, notes: body.notes ?? null, matchScore,
        responded: RESPONDED.includes(status), updatedAt: iso(), interviews: [],
      };
      s.applications.unshift(a);
      return done(a);
    }
    const a = s.applications.find((x) => x.id === p[1]);
    if (!a) throw new LocalError(404, 'Application not found');
    if (method === 'DELETE') {
      s.applications = s.applications.filter((x) => x.id !== a.id);
      return done(undefined);
    }
    if (p[2] === 'interviews') {
      const i = { id: uid('i'), round: body.round, scheduledAt: new Date(body.scheduledAt).toISOString(), outcome: null };
      a.interviews.push(i);
      a.status = 'INTERVIEWING';
      a.responded = true;
      a.updatedAt = iso();
      return done(i);
    }
    if (method === 'PATCH') {
      if (body.status && body.status !== a.status) {
        if (body.status === 'APPLIED' && !a.appliedAt) {
          a.appliedAt = iso();
          a.followUpAt = iso(7);
        }
        if (RESPONDED.includes(body.status)) a.responded = true;
        if (['REJECTED', 'WITHDRAWN', 'ACCEPTED', 'OFFER'].includes(body.status)) a.followUpAt = null;
      }
      const { appliedAt, followUpAt, jobId: _j, ...rest } = body;
      Object.assign(a, rest, appliedAt ? { appliedAt: new Date(appliedAt).toISOString() } : {}, followUpAt ? { followUpAt: new Date(followUpAt).toISOString() } : {}, { updatedAt: iso() });
      return done(a);
    }
    return done(a, false);
  }

  throw new LocalError(404, `Not available in the browser edition: ${method} ${url.pathname}`);
}

async function withJob(s: State, d: Doc) {
  const imported = s.imported.find((j) => j.id === d.jobId);
  const job = imported ?? (await loadIndex()).byId.get(d.jobId);
  return { ...d, job: job ? { id: job.id, title: job.title, companyName: job.company, url: job.url } : null };
}
