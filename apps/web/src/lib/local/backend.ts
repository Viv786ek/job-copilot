/**
 * Browser implementation of the platform API for the GitHub Pages edition. Same routes and
 * response shapes as apps/api. Data: the real harvested job index + the user's own resume,
 * persisted in this browser's localStorage. Nothing is sent to any server except, if the user
 * adds one, their own Gemini API key calls to Google.
 */

const KEY = 'job-copilot-local-v3';
const LEGACY_KEYS = ['job-copilot-demo-v1', 'job-copilot-demo-v2'];
const DAY = 86_400_000;
const RESPONDED = ['SCREENING', 'INTERVIEWING', 'OFFER', 'ACCEPTED', 'REJECTED'];

interface StoredResume {
  id: string;
  fileName: string;
  createdAt: string;
  rawText: string;
  parsed: ParsedResume;
  health: HealthReport;
  parser: 'built-in' | 'gemini';
  /** How the profile was provided: resume file, LinkedIn PDF export, or pasted text. */
  origin?: 'resume' | 'linkedin-pdf' | 'linkedin-text' | 'pasted';
}
interface Preferences {
  titles: string[];
  locations: string[];
  countries: string[];
  authorizedCountries: string[];
  openToRelocation: boolean;
  remoteOnly: boolean;
  workModes: string[];
  includeInternational: boolean;
  needsVisaSponsorship: boolean;
  minMatchScore: number;
  autoGenerateDocs: boolean;
  digestFrequency: string;
  /** Discovery preferences (Phase 1 of the AI Job Discovery flow). */
  experienceLevel: string;
  salaryFloor: number | null;
  salaryCurrency: string;
  linkedinUrl: string | null;
  discoveryCompletedAt: string | null;
}
interface Doc {
  id: string;
  type: string;
  jobId: string;
  version: number;
  content: any;
  atsScoreBefore: number | null;
  atsScoreAfter: number | null;
  guardrailFlags: string[];
  model: string;
  createdAt: string;
}
interface App {
  id: string;
  jobId: string | null;
  company: string;
  role: string;
  source: string;
  jobUrl: string | null;
  status: string;
  appliedAt: string | null;
  followUpAt: string | null;
  recruiterName: string | null;
  recruiterEmail: string | null;
  notes: string | null;
  matchScore: number | null;
  responded: boolean;
  updatedAt: string;
  interviews: Array<{ id: string; round: string; scheduledAt: string; outcome: string | null }>;
}
interface ImportedJob extends IndexedJob {
  detail: JobDetail;
}
interface State {
  v: 3;
  resumes: StoredResume[];
  activeResumeId: string | null;
  profile: { headline: string | null; location: string | null; summary: string | null; skills: string[] } | null;
  preferences: Preferences;
  flags: Record<string, { saved?: boolean; dismissed?: boolean }>;
  imported: ImportedJob[];
  documents: Doc[];
  applications: App[];
}

const uid = (p: string) => `${p}-${Math.random().toString(36).slice(2, 10)}${Date.now().toString(36).slice(-4)}`;
const iso = (offsetDays = 0) => new Date(Date.now() + offsetDays * DAY).toISOString();

function fresh(): State {
  return {
    v: 3,
    resumes: [],
    activeResumeId: null,
    profile: null,
    preferences: {
      titles: [],
      locations: [],
      countries: [],
      authorizedCountries: [],
      openToRelocation: false,
      remoteOnly: false,
      workModes: [],
      includeInternational: true,
      needsVisaSponsorship: false,
      minMatchScore: 60,
      autoGenerateDocs: false,
      digestFrequency: 'OFF',
      experienceLevel: '',
      salaryFloor: null,
      salaryCurrency: 'USD',
      linkedinUrl: null,
      discoveryCompletedAt: null,
    },
    flags: {},
    imported: [],
    documents: [],
    applications: [],
  };
}

function load(): State {
  if (typeof window === 'undefined') return fresh();
  try {
    for (const k of LEGACY_KEYS) window.localStorage.removeItem(k);
    const raw = window.localStorage.getItem(KEY);
    if (raw) {
      const s = JSON.parse(raw) as State;
      if (s.v === 3) return { ...fresh(), ...s, preferences: { ...fresh().preferences, ...s.preferences } };
    }
  } catch {
    /* unavailable or corrupt: start clean */
  }
  return fresh();
}

function save(s: State) {
  try {
    window.localStorage.setItem(KEY, JSON.stringify(s));
  } catch {
    throw new LocalError(507, 'Browser storage is full or blocked. Delete old resumes or documents and try again.');
  }
  scoreCache.clear();
}

export function resetLocalData() {
  try {
    window.localStorage.removeItem(KEY);
  } catch {
    /* ignore */
  }
  scoreCache.clear();
}

export class LocalError extends Error {
  constructor(
    public status: number,
    message: string,
  ) {
    super(message);
  }
}

