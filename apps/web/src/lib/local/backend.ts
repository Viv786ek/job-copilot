function activeResume(s: State): StoredResume | null {
  return s.resumes.find((r) => r.id === s.activeResumeId) ?? s.resumes[0] ?? null;
}

function candidate(s: State): CandidateFeatures | null {
  const r = activeResume(s);
  if (!r || !s.profile) return null;
  return {
    skills: s.profile.skills,
    totalYearsExp: computeYearsOfExperience(r.parsed),
    targetTitles: [...s.preferences.titles, ...r.parsed.experience.slice(0, 3).map((e) => e.title), s.profile.headline ?? ''].filter(Boolean),
    embedding: [],
    resumeText: r.rawText,
    preferredLocations: s.preferences.locations,
    remoteOnly: s.preferences.remoteOnly,
    needsVisaSponsorship: s.preferences.needsVisaSponsorship,
    targetCountries: s.preferences.countries,
    authorizedCountries: s.preferences.authorizedCountries,
    openToRelocation: s.preferences.openToRelocation,
  };
}

const scoreCache = new Map<string, MatchResult>();

function score(c: CandidateFeatures, j: IndexedJob, d?: JobDetail | null): MatchResult {
  const cacheable = !d;
  if (cacheable) {
    const hit = scoreCache.get(j.id);
    if (hit) return hit;
  }
  const r = computeMatch(c, {
    title: j.title,
    requiredSkills: d?.analysis.requiredSkills ?? j.requiredSkills,
    preferredSkills: d?.analysis.preferredSkills ?? j.preferredSkills,
    atsKeywords: d?.analysis.atsKeywords ?? [...j.requiredSkills, ...j.preferredSkills],
    minYears: d?.analysis.minYears ?? j.minYears,
    maxYears: d?.analysis.maxYears ?? null,
    embedding: [],
    location: j.location,
    workMode: j.workMode,
    visaSponsorship: null,
    country: j.countries[0] ?? null,
    countries: j.countries,
    remoteScope: j.remoteScope,
    visaStatus: j.visaStatus,
  });
  if (cacheable) scoreCache.set(j.id, r);
  return r;
}

async function allJobs(s: State): Promise<IndexedJob[]> {
  const { jobs } = await loadIndex();
  return s.imported.length ? [...s.imported, ...jobs] : jobs;
}

async function findJob(s: State, id: string): Promise<{ job: IndexedJob; detail: JobDetail | null }> {
  const imported = s.imported.find((j) => j.id === id);
  if (imported) return { job: imported, detail: imported.detail };
  const { byId } = await loadIndex();
  const job = byId.get(id);
  if (!job) throw new LocalError(404, 'This job is no longer in the current dataset (it may have closed).');
  return { job, detail: await loadDetail(id) };
}

function regionsCovering(countries: string[]) {
  return Object.entries(REGIONS)
    .filter(([, r]) => r.countries.some((c) => countries.includes(c)))
    .map(([k]) => k);
}

function summary(j: IndexedJob) {
  return {
    id: j.id,
    title: j.title,
    companyName: j.company,
    location: j.location || null,
    workMode: j.workMode,
    source: j.source,
    url: j.url,
    salaryMin: j.salaryMin,
    salaryMax: j.salaryMax,
    salaryCurrency: j.salaryCurrency,
    visaSponsorship: j.visaStatus === 'SPONSORS' ? true : j.visaStatus === 'NO_SPONSORSHIP' ? false : null,
    visaStatus: j.visaStatus,
    visaConfidence: j.visaConfidence,
    relocation: j.relocation,
    countries: j.countries,
    remoteScope: j.remoteScope,
    postedAt: j.postedAt,
    firstSeenAt: j.firstSeenAt,
    alsoOnCount: j.alsoOnCount,
    minYears: j.minYears,
  };
}

function matchRow(j: IndexedJob, m: MatchResult | null, s: State, c: CandidateFeatures | null) {
  return {
    id: j.id,
    score: m ? m.score : null,
    atsScore: m ? m.atsScore : null,
    breakdown: m?.breakdown ?? {},
    matchedSkills: m?.matchedSkills ?? [],
    missingSkills: m ? [...m.missingRequiredSkills, ...m.missingPreferredSkills] : [],
    missingKeywords: m?.missingKeywords ?? [],
    recommendations: m?.recommendations ?? [],
    reasons: m && c ? explainMatch(m, j, { targetCountries: c.targetCountries ?? [], authorizedCountries: c.authorizedCountries ?? [], totalYearsExp: c.totalYearsExp }) : [],
    saved: !!s.flags[j.id]?.saved,
    job: summary(j),
  };
}

/** Experience bands for the level filter (years required by the posting). */
const LEVELS: Record<string, (minYears: number | null, title: string) => boolean> = {
  entry: (y, t) => (y != null ? y <= 2 : /\b(junior|jr|graduate|entry|intern|associate)\b/i.test(t)),
  mid: (y, t) => (y != null ? y >= 2 && y <= 5 : !/\b(senior|sr|staff|principal|lead|head|director|junior|intern)\b/i.test(t)),
  senior: (y, t) => (y != null ? y >= 5 : /\b(senior|sr|staff|principal|lead)\b/i.test(t)),
  leadership: (_y, t) => /\b(head|director|vp|vice president|chief|manager|lead)\b/i.test(t),
};

async function ingestProfileText(s: State, rawText: string, fileName: string, origin: StoredResume['origin']) {
  let parsed: ParsedResume;
  let parser: StoredResume['parser'] = 'built-in';
  if (getAiKey()) {
    try {
      parsed = await geminiJson(ParsedResumeSchema, prompts.parseResume(rawText));
      parser = 'gemini';
    } catch {
      parsed = parseResumeText(rawText);
    }
  } else parsed = parseResumeText(rawText);
  parsed = { ...parsed, skills: normalizeSkills([...parsed.skills, ...parsed.experience.flatMap((e) => e.skills), ...extractKnownSkills(rawText)]) };
  const r: StoredResume = { id: uid('resume'), fileName, createdAt: iso(), rawText, parsed, health: scoreResumeHealth(parsed, rawText), parser, origin };
  s.resumes.unshift(r);
  s.activeResumeId = r.id;
  s.profile = { headline: parsed.headline ?? parsed.experience[0]?.title ?? null, location: parsed.location ?? null, summary: parsed.summary ?? null, skills: parsed.skills };
  if (!s.preferences.titles.length) s.preferences.titles = [...new Set(parsed.experience.slice(0, 2).map((e) => e.title))].filter((t) => t && t !== 'Role');
  return r;
}

