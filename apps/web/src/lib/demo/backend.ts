/**
 * In-browser implementation of the REST API for the static GitHub Pages demo.
 * Same routes and response shapes as apps/api, persisted to localStorage.
 * Scoring, ATS coverage, resume health and honesty guardrails are the real shared code.
 */

const KEY = 'job-copilot-demo-v2';
const DAY = 86_400_000;

interface Job {
  id: string; title: string; companyName: string; location: string | null; workMode: 'REMOTE' | 'HYBRID' | 'ONSITE' | null;
  source: string; url: string; salaryMin: number | null; salaryMax: number | null; salaryCurrency: string | null;
  visaSponsorship: boolean | null; postedAt: string; description: string; analysis: JdAnalysis; employmentType: null;
}
interface Match {
  id: string; jobId: string; score: number; atsScore: number; breakdown: MatchResult['breakdown']; matchedSkills: string[];
  missingSkills: string[]; missingKeywords: string[]; recommendations: string[]; saved: boolean; dismissed: boolean; createdAt: string;
}
interface Doc {
  id: string; type: string; jobId: string; version: number; content: any; atsScoreBefore: number | null; atsScoreAfter: number | null;
  guardrailFlags: string[]; createdAt: string;
}
interface App {
  id: string; jobId: string | null; company: string; role: string; source: string; jobUrl: string | null; status: string;
  appliedAt: string | null; followUpAt: string | null; recruiterName: string | null; recruiterEmail: string | null; notes: string | null;
  matchScore: number | null; responded: boolean; updatedAt: string; interviews: Array<{ id: string; round: string; scheduledAt: string; outcome: string | null }>;
}
interface State {
  resumes: Array<{ id: string; fileName: string; createdAt: string }>;
  profileSkills: string[];
  headline: string | null; location: string | null; summary: string | null;
  preferences: { titles: string[]; locations: string[]; remoteOnly: boolean; includeInternational: boolean; needsVisaSponsorship: boolean; minMatchScore: number; autoGenerateDocs: boolean; digestFrequency: string };
  jobs: Job[]; matches: Match[]; documents: Doc[]; applications: App[];
}

const uid = (p: string) => `${p}-${Math.random().toString(36).slice(2, 10)}`;
const iso = (offsetDays = 0) => new Date(Date.now() + offsetDays * DAY).toISOString();
const RESPONDED = ['SCREENING', 'INTERVIEWING', 'OFFER', 'ACCEPTED', 'REJECTED'];

function rawText() {
  return resumeToText(SAMPLE_RESUME);
}

function features(s: State) {
  return {
    skills: s.profileSkills,
    totalYearsExp: computeYearsOfExperience(SAMPLE_RESUME),
    targetTitles: [...s.preferences.titles, ...SAMPLE_RESUME.experience.map((e) => e.title)],
    embedding: [],
    resumeText: rawText(),
    preferredLocations: s.preferences.locations,
    remoteOnly: s.preferences.remoteOnly,
    needsVisaSponsorship: s.preferences.needsVisaSponsorship,
  };
}

function scoreJob(s: State, job: Job): MatchResult {
  const a = job.analysis;
  return computeMatch(features(s), {
    title: job.title, requiredSkills: a.requiredSkills, preferredSkills: a.preferredSkills, atsKeywords: a.atsKeywords,
    minYears: a.minYearsExperience ?? null, maxYears: a.maxYearsExperience ?? null, embedding: [], location: job.location,
    workMode: job.workMode, visaSponsorship: job.visaSponsorship, country: null,
  });
}

function upsertMatch(s: State, job: Job) {
  const r = scoreJob(s, job);
  const existing = s.matches.find((m) => m.jobId === job.id);
  const data = {
    score: r.score, atsScore: r.atsScore, breakdown: r.breakdown, matchedSkills: r.matchedSkills,
    missingSkills: [...r.missingRequiredSkills, ...r.missingPreferredSkills], missingKeywords: r.missingKeywords, recommendations: r.recommendations,
  };
  if (existing) Object.assign(existing, data);
  else s.matches.push({ id: uid('m'), jobId: job.id, saved: false, dismissed: false, createdAt: iso(), ...data });
  return r;
}

function seed(): State {
  const s: State = {
    resumes: [{ id: 'resume-sample', fileName: 'Aarav_Sharma_Resume.pdf', createdAt: iso(-14) }],
    profileSkills: SAMPLE_RESUME.skills,
    headline: SAMPLE_RESUME.headline ?? null, location: SAMPLE_RESUME.location ?? null, summary: SAMPLE_RESUME.summary ?? null,
    preferences: { titles: ['Full Stack Developer', 'Frontend Engineer'], locations: ['Bengaluru'], remoteOnly: false, includeInternational: true, needsVisaSponsorship: false, minMatchScore: 60, autoGenerateDocs: true, digestFrequency: 'DAILY' },
    jobs: [], matches: [], documents: [], applications: [],
  };
  for (const j of SEED_JOBS) {
    const job: Job = {
      ...j, url: `https://example.com/jobs/${j.id}`, postedAt: iso(-j.daysAgo), employmentType: null,
      analysis: analyzeJdHeuristic(j.description, j.title),
    };
    s.jobs.push(job);
    upsertMatch(s, job);
  }
  const app = (jobId: string, status: string, appliedDaysAgo: number | null, extra: Partial<App> = {}): App => {
    const j = s.jobs.find((x) => x.id === jobId)!;
    return {
      id: uid('a'), jobId, company: j.companyName, role: j.title, source: j.source, jobUrl: j.url, status,
      appliedAt: appliedDaysAgo == null ? null : iso(-appliedDaysAgo), followUpAt: appliedDaysAgo == null ? null : iso(7 - appliedDaysAgo),
      recruiterName: null, recruiterEmail: null, notes: null, matchScore: s.matches.find((m) => m.jobId === jobId)?.score ?? null,
      responded: RESPONDED.includes(status), updatedAt: iso(-(appliedDaysAgo ?? 0)), interviews: [], ...extra,
    };
  };
  s.applications = [
    app('job-react-kestrel', 'INTERVIEWING', 12, { recruiterName: 'Priya (Talent)', followUpAt: null, interviews: [{ id: uid('i'), round: 'Technical 1', scheduledAt: iso(2), outcome: null }] }),
    app('job-fullstack-tidal', 'SCREENING', 9, { followUpAt: null }),
    app('job-node-orbit', 'APPLIED', 8),
    app('job-angular-cobalt', 'REJECTED', 20, { followUpAt: null }),
    app('job-fullstack-northwind', 'DRAFT', null),
    app('job-platform-aster', 'APPLIED', 3),
  ];
  return s;
}

function load(): State {
  if (typeof window === 'undefined') return seed();
  try {
    const raw = window.localStorage.getItem(KEY);
    if (raw) return JSON.parse(raw) as State;
  } catch {
    /* storage unavailable or corrupt: fall back to fresh seed */
  }
  const s = seed();
  save(s);
  return s;
}

function save(s: State) {
  try {
    window.localStorage.setItem(KEY, JSON.stringify(s));
  } catch {
    /* private mode: demo still works for this page view */
  }
}

export function resetDemo() {
  try {
    window.localStorage.removeItem(KEY);
  } catch {
    /* ignore */
  }
}

class DemoError extends Error {
  constructor(public status: number, message: string) {
    super(message);
  }
}

function wordDoc(title: string, bodyHtml: string): { url: string } {
  const html = `<html><head><meta charset="utf-8"><title>${title}</title></head><body style="font-family:Calibri,Arial;font-size:11pt">${bodyHtml}</body></html>`;
  return { url: URL.createObjectURL(new Blob([html], { type: 'application/msword' })) };
}

const esc = (t: string) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function resumeHtml(c: any) {
  const r = SAMPLE_RESUME;
  return `<h1 style="text-align:center;margin:0">${esc(r.fullName ?? '')}</h1>
<p style="text-align:center">${esc([r.email, r.phone, r.location, ...r.links].filter(Boolean).join(' | '))}</p>
<p style="text-align:center"><i>${esc(c.headline)}</i></p>
<h3>SUMMARY</h3><p>${esc(c.summary)}</p>
<h3>SKILLS</h3><p>${esc(c.skills.join(' • '))}</p>
<h3>EXPERIENCE</h3>${c.experience
    .map((e: any) => `<p><b>${esc(e.title)}, ${esc(e.company)}</b> (${e.startDate ?? ''} – ${e.current ? 'Present' : e.endDate ?? ''})</p><ul>${e.bullets.map((b: string) => `<li>${esc(b)}</li>`).join('')}</ul>`)
    .join('')}
<h3>PROJECTS</h3>${c.projects.map((p: any) => `<p><b>${esc(p.name)}</b>: ${esc(p.description)}</p>`).join('')}
<h3>EDUCATION</h3>${c.education.map((e: any) => `<p>${esc([e.degree, e.field].filter(Boolean).join(', '))} — ${esc(e.institution)}</p>`).join('')}
<h3>CERTIFICATIONS</h3>${c.certifications.map((x: any) => `<p>${esc(x.name)}</p>`).join('')}`;
}

function dashboard(s: State) {
  const active = s.matches.filter((m) => !m.dismissed);
  const pipeline: Record<string, number> = {};
  for (const a of s.applications) pipeline[a.status] = (pipeline[a.status] ?? 0) + 1;
  const applied = s.applications.filter((a) => a.status !== 'DRAFT').length;
  const responded = s.applications.filter((a) => RESPONDED.includes(a.status)).length;
  const resumes = s.documents.filter((d) => d.type === 'TAILORED_RESUME' && d.atsScoreBefore != null);
  const avg = (xs: number[]) => (xs.length ? Math.round(xs.reduce((a, b) => a + b, 0) / xs.length) : 0);
  const before = avg(resumes.map((d) => d.atsScoreBefore!));
  const after = avg(resumes.map((d) => d.atsScoreAfter!));
  const missing = new Map<string, number>();
  for (const m of active.filter((m) => m.score >= 50)) for (const k of m.missingSkills) missing.set(k, (missing.get(k) ?? 0) + 1);
  const weeks = new Map<string, { applied: number; responses: number }>();
  for (const a of s.applications.filter((a) => a.appliedAt)) {
    const d = new Date(a.appliedAt!);
    d.setDate(d.getDate() - ((d.getDay() + 6) % 7));
    const k = d.toISOString().slice(0, 10);
    const w = weeks.get(k) ?? { applied: 0, responses: 0 };
    w.applied++;
    if (RESPONDED.includes(a.status)) w.responses++;
    weeks.set(k, w);
  }
  const interviews = s.applications.flatMap((a) => a.interviews);
  return {
    resumeHealth: scoreResumeHealth(SAMPLE_RESUME, rawText()).score,
    avgMatchScore: avg(active.map((m) => m.score)),
    topMatches: active.filter((m) => m.score >= 75).length,
    atsImprovement: { avgBefore: before, avgAfter: after, delta: after - before, documents: resumes.length },
    pipeline,
    applied,
    interviews: interviews.length,
    upcomingInterviews: interviews.filter((i) => new Date(i.scheduledAt) > new Date()).length,
    rejections: pipeline.REJECTED ?? 0,
    offers: (pipeline.OFFER ?? 0) + (pipeline.ACCEPTED ?? 0),
    responseRate: applied ? Math.round((responded / applied) * 100) : 0,
    followUpsDue: s.applications.filter((a) => a.followUpAt && new Date(a.followUpAt) <= new Date() && !a.responded && ['APPLIED', 'SCREENING'].includes(a.status)).length,
    weekly: [...weeks.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([week, v]) => ({ week, ...v })),
    topMissingSkills: [...missing.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([skill, count]) => ({ skill, count })),
  };
}

function jobSummary(j: Job) {
  const { description: _d, analysis: _a, ...rest } = j;
  return rest;
}

function createDoc(s: State, jobId: string, type: string, content: unknown, extra: Partial<Doc> = {}) {
  const version = s.documents.filter((d) => d.jobId === jobId && d.type === type).length + 1;
  const doc: Doc = { id: uid('d'), type, jobId, version, content, atsScoreBefore: null, atsScoreAfter: null, guardrailFlags: [], createdAt: iso(), ...extra };
  s.documents.unshift(doc);
  return doc;
}

function withJob(s: State, d: Doc) {
  const j = s.jobs.find((x) => x.id === d.jobId);
  return { ...d, job: j ? { id: j.id, title: j.title, companyName: j.companyName, url: j.url } : null };
}

function importJob(s: State, body: { url?: string; description?: string; title?: string; company?: string; location?: string }) {
  if (!body.description || body.description.length < 100) {
    throw new DemoError(400, 'The demo cannot fetch external pages. Paste the job description text (100+ characters).');
  }
  const analysis = analyzeJdHeuristic(body.description, body.title);
  const job: Job = {
    id: uid('job'), title: body.title || analysis.title || 'Imported role', companyName: body.company || 'Imported company',
    location: body.location ?? null, workMode: analysis.workMode ?? null, source: 'MANUAL', url: body.url || '',
    salaryMin: null, salaryMax: null, salaryCurrency: null, visaSponsorship: analysis.visaSponsorship ?? null,
    postedAt: iso(), description: body.description, analysis, employmentType: null,
  };
  s.jobs.unshift(job);
  const match = upsertMatch(s, job);
  return { jobId: job.id, match };
}

/** Routes a request exactly like the NestJS API would. */
export async function demoRequest<T>(path: string, init: RequestInit = {}): Promise<T> {
  await new Promise((r) => setTimeout(r, 250)); // feel like a network call
  const method = (init.method ?? 'GET').toUpperCase();
  const url = new URL(path, 'http://demo');
  const p = url.pathname.split('/').filter(Boolean);
  const q = url.searchParams;
  const body = typeof init.body === 'string' ? JSON.parse(init.body) : {};
  const s = load();
  const done = <R,>(v: R) => (save(s), v as unknown as T);

  // ---- dashboard
  if (p[0] === 'dashboard') return done(dashboard(s));

  // ---- profile
  if (p[0] === 'profile') {
    if (method === 'GET')
      return done({
        profile: { headline: s.headline, location: s.location, summary: s.summary, skills: s.profileSkills, totalYearsExp: computeYearsOfExperience(SAMPLE_RESUME) },
        preferences: s.preferences,
      });
    if (p[1] === 'preferences') {
      Object.assign(s.preferences, body);
    } else {
      // As in production, the profile skill list is the user's own declaration; scores are recomputed below.
      if (body.skills) s.profileSkills = body.skills;
      Object.assign(s, { headline: body.headline ?? s.headline, location: body.location ?? s.location, summary: body.summary ?? s.summary });
    }
    s.jobs.forEach((j) => upsertMatch(s, j));
    return done({ ok: true });
  }

  // ---- resumes
  if (p[0] === 'resumes') {
    const health = scoreResumeHealth(SAMPLE_RESUME, rawText());
    const view = (r: State['resumes'][number]) => ({ ...r, status: 'PARSED', healthScore: health.score, errorMessage: null });
    if (method === 'GET' && !p[1]) return done(s.resumes.map(view));
    if (method === 'POST' && !p[1]) {
      const file = init.body instanceof FormData ? (init.body.get('file') as File | null) : null;
      const r = { id: uid('resume'), fileName: file?.name ?? 'resume.pdf', createdAt: iso() };
      s.resumes.unshift(r);
      return done(view(r));
    }
    const r = s.resumes.find((x) => x.id === p[1]);
    if (!r) throw new DemoError(404, 'Resume not found');
    if (method === 'DELETE') {
      s.resumes = s.resumes.filter((x) => x.id !== r.id);
      return done(undefined);
    }
    if (p[2] === 'download') return done(wordDoc(r.fileName, `<pre>${esc(rawText())}</pre>`));
    if (method === 'POST') return done({ ok: true });
    return done({ ...view(r), parsed: SAMPLE_RESUME, healthReport: health });
  }

  // ---- jobs
  if (p[0] === 'jobs') {
    if (p[1] === 'feed') {
      const page = Number(q.get('page') ?? 1);
      const pageSize = 20;
      const minScore = Number(q.get('minScore') ?? 0);
      const term = (q.get('q') ?? '').toLowerCase();
      const rows = s.matches
        .filter((m) => !m.dismissed && m.score >= minScore && (q.get('saved') !== 'true' || m.saved))
        .map((m) => ({ ...m, job: s.jobs.find((j) => j.id === m.jobId)! }))
        .filter((m) => m.job && (q.get('remote') !== 'true' || m.job.workMode === 'REMOTE') && (!q.get('source') || m.job.source === q.get('source')))
        .filter((m) => !term || m.job.title.toLowerCase().includes(term) || m.job.companyName.toLowerCase().includes(term))
        .sort((a, b) => b.score - a.score);
      return done({ items: rows.slice((page - 1) * pageSize, page * pageSize).map((m) => ({ ...m, job: jobSummary(m.job) })), total: rows.length, page, pageSize });
    }
    if (p[1] === 'import') return done(importJob(s, body));
    if (p[1] === 'analyze') {
      if (!body.description || body.description.length < 100) throw new DemoError(400, 'Paste at least 100 characters of the job description');
      const analysis = analyzeJdHeuristic(body.description, body.title);
      const match = computeMatch(features(s), {
        title: body.title ?? '', requiredSkills: analysis.requiredSkills, preferredSkills: analysis.preferredSkills, atsKeywords: analysis.atsKeywords,
        minYears: analysis.minYearsExperience ?? null, maxYears: analysis.maxYearsExperience ?? null, embedding: [], location: null,
        workMode: analysis.workMode ?? null, visaSponsorship: analysis.visaSponsorship ?? null, country: null,
      });
      return done({ analysis, match });
    }
    if (p[1] === 'search') return done({ queued: true });
    if (p[1] === 'career-pages') return done({ supported: false, message: 'Career page tracking runs on the server in production.' });
    const job = s.jobs.find((j) => j.id === p[1]);
    if (!job) throw new DemoError(404, 'Job not found');
    const match = s.matches.find((m) => m.jobId === job.id) ?? null;
    if (method === 'PATCH') {
      if (match) Object.assign(match, body);
      return done(match);
    }
    return done({
      job,
      match,
      documents: s.documents.filter((d) => d.jobId === job.id).map(({ id, type, version }) => ({ id, type, version })),
    });
  }

  // ---- documents
  if (p[0] === 'documents') {
    if (method === 'POST') {
      const job = s.jobs.find((j) => j.id === body.jobId);
      if (!job) throw new DemoError(404, 'Job not found');
      const a = job.analysis;
      if (p[1] === 'tailored-resume') {
        const { resume, flags } = gen.tailorResume(SAMPLE_RESUME, rawText(), a);
        const have = new Set(s.profileSkills.map(skillKey));
        const missing = [...a.requiredSkills, ...a.preferredSkills].filter((k) => !have.has(skillKey(k)));
        const before = atsKeywordCoverage(rawText(), a.atsKeywords);
        const after = atsKeywordCoverage(tailoredToText(resume), a.atsKeywords);
        return done(createDoc(s, job.id, 'TAILORED_RESUME', { ...resume, missingSkills: missing }, {
          atsScoreBefore: Math.round(before.ratio * 100), atsScoreAfter: Math.round(after.ratio * 100), guardrailFlags: flags,
        }));
      }
      if (p[1] === 'cover-letter') return done(createDoc(s, job.id, 'COVER_LETTER', gen.coverLetter(SAMPLE_RESUME, job, a)));
      if (p[1] === 'outreach') return done(createDoc(s, job.id, 'RECRUITER_EMAIL', gen.outreach(SAMPLE_RESUME, job)));
      if (p[1] === 'interview-prep') return done(createDoc(s, job.id, 'INTERVIEW_PREP', gen.interviewPrep(SAMPLE_RESUME, job, a)));
    }
    if (method === 'GET' && !p[1]) {
      const type = q.get('type');
      return done(s.documents.filter((d) => !type || d.type === type).map((d) => withJob(s, d)));
    }
    const doc = s.documents.find((d) => d.id === p[1]);
    if (!doc) throw new DemoError(404, 'Document not found');
    if (p[2] === 'docx') {
      return done(
        doc.type === 'TAILORED_RESUME'
          ? wordDoc('Tailored resume', resumeHtml(doc.content))
          : wordDoc('Cover letter', doc.content.body.split('\n').map((l: string) => `<p>${esc(l)}</p>`).join('')),
      );
    }
    return done(withJob(s, doc));
  }

  // ---- applications
  if (p[0] === 'applications') {
    if (p[1] === 'interviews') return done(s.applications.flatMap((a) => a.interviews.map((i) => ({ ...i, application: { id: a.id, company: a.company, role: a.role } }))));
    if (method === 'GET' && !p[1]) {
      const status = q.get('status');
      const term = (q.get('q') ?? '').toLowerCase();
      return done(
        s.applications
          .filter((a) => (!status || a.status === status) && (!term || a.company.toLowerCase().includes(term) || a.role.toLowerCase().includes(term)))
          .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)),
      );
    }
    if (method === 'POST' && !p[1]) {
      const status = body.status ?? 'DRAFT';
      const appliedAt = body.appliedAt ? new Date(body.appliedAt).toISOString() : status !== 'DRAFT' ? iso() : null;
      const a: App = {
        id: uid('a'), jobId: body.jobId ?? null, company: body.company, role: body.role, source: body.source, jobUrl: body.jobUrl ?? null,
        status, appliedAt, followUpAt: body.followUpAt ? new Date(body.followUpAt).toISOString() : appliedAt ? new Date(Date.parse(appliedAt) + 7 * DAY).toISOString() : null,
        recruiterName: body.recruiterName ?? null, recruiterEmail: body.recruiterEmail ?? null, notes: body.notes ?? null,
        matchScore: s.matches.find((m) => m.jobId === body.jobId)?.score ?? null, responded: RESPONDED.includes(status), updatedAt: iso(), interviews: [],
      };
      s.applications.unshift(a);
      return done(a);
    }
    const a = s.applications.find((x) => x.id === p[1]);
    if (!a) throw new DemoError(404, 'Application not found');
    if (method === 'DELETE') {
      s.applications = s.applications.filter((x) => x.id !== a.id);
      return done(undefined);
    }
    if (p[2] === 'interviews') {
      const i = { id: uid('i'), round: body.round, scheduledAt: new Date(body.scheduledAt).toISOString(), outcome: null };
      a.interviews.push(i);
      a.status = 'INTERVIEWING';
      a.responded = true;
      return done(i);
    }
    if (method === 'PATCH') {
      if (body.status && body.status !== a.status) {
        if (body.status === 'APPLIED' && !a.appliedAt) {
          a.appliedAt = iso();
          a.followUpAt = iso(7);
        }
        if (RESPONDED.includes(body.status)) a.responded = true;
        if (['REJECTED', 'WITHDRAWN', 'ACCEPTED', 'OFFER'].includes(body.status)) a.followUpAt = null;
      }
      const { appliedAt, followUpAt, jobId: _j, ...rest } = body;
      Object.assign(a, rest, appliedAt ? { appliedAt: new Date(appliedAt).toISOString() } : {}, followUpAt ? { followUpAt: new Date(followUpAt).toISOString() } : {}, { updatedAt: iso() });
      return done(a);
    }
    return done(a);
  }

  throw new DemoError(404, `Not available in the demo: ${method} ${url.pathname}`);
}
