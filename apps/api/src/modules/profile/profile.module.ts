import { Body, Controller, Get, Injectable, Module, Patch } from '@nestjs/common';
import { ApiBearerAuth, ApiTags } from '@nestjs/swagger';
import { normalizeSkills, toCountryCode } from '@copilot/shared';
import { z } from 'zod';
import { AuthUser, CurrentUser } from '../../common/auth';
import { ZodPipe } from '../../common/zod.pipe';
import { PrismaService } from '../../core/prisma.service';

const ProfilePatch = z.object({
  headline: z.string().max(200).optional(),
  location: z.string().max(200).optional(),
  summary: z.string().max(2000).optional(),
  /** Users can add skills they genuinely have but the parser missed; this is the only source of truth for tailoring. */
  skills: z.array(z.string().max(60)).max(150).optional(),
});

/** Accepts ISO codes or country names ("Germany", "UAE"); stores ISO alpha-2. */
const IsoCountries = z
  .array(z.string().max(60))
  .max(60)
  .transform((list, ctx) => {
    const out: string[] = [];
    for (const v of list) {
      const code = toCountryCode(v);
      if (!code) ctx.addIssue({ code: z.ZodIssueCode.custom, message: `Unknown country: ${v}` });
      else if (!out.includes(code)) out.push(code);
    }
    return out;
  });

const PreferencesPatch = z.object({
  titles: z.array(z.string().max(100)).max(5).optional(),
  locations: z.array(z.string().max(100)).max(5).optional(),
  remoteOnly: z.boolean().optional(),
  includeInternational: z.boolean().optional(),
  needsVisaSponsorship: z.boolean().optional(),
  minSalary: z.number().int().min(0).nullable().optional(),
  currency: z.string().length(3).optional(),
  minMatchScore: z.number().int().min(0).max(100).optional(),
  sources: z.array(z.string().max(30)).optional(),
  autoGenerateDocs: z.boolean().optional(),
  digestFrequency: z.enum(['DAILY', 'WEEKLY', 'OFF']).optional(),
  countries: IsoCountries.optional(),
  authorizedCountries: IsoCountries.optional(),
  openToRelocation: z.boolean().optional(),
  workModes: z.array(z.enum(['REMOTE', 'HYBRID', 'ONSITE'])).optional(),
});

@Injectable()
export class ProfileService {
  constructor(private readonly prisma: PrismaService) {}

  async get(userId: string) {
    const [profile, preferences] = await Promise.all([
      this.prisma.candidateProfile.findUnique({ where: { userId }, omit: { embedding: true } }),
      this.prisma.jobPreference.findUnique({ where: { userId } }),
    ]);
    return { profile, preferences };
  }

  updateProfile(userId: string, patch: z.infer<typeof ProfilePatch>) {
    return this.prisma.candidateProfile.update({
      where: { userId },
      data: { ...patch, skills: patch.skills ? normalizeSkills(patch.skills) : undefined },
      omit: { embedding: true },
    });
  }

  updatePreferences(userId: string, patch: z.infer<typeof PreferencesPatch>) {
    return this.prisma.jobPreference.upsert({ where: { userId }, update: patch, create: { userId, ...patch } });
  }
}

@ApiTags('profile')
@ApiBearerAuth()
@Controller('profile')
export class ProfileController {
  constructor(private readonly svc: ProfileService) {}

  @Get()
  get(@CurrentUser() u: AuthUser) {
    return this.svc.get(u.id);
  }

  @Patch()
  update(@CurrentUser() u: AuthUser, @Body(new ZodPipe(ProfilePatch)) b: z.infer<typeof ProfilePatch>) {
    return this.svc.updateProfile(u.id, b);
  }

  @Patch('preferences')
  prefs(@CurrentUser() u: AuthUser, @Body(new ZodPipe(PreferencesPatch)) b: z.infer<typeof PreferencesPatch>) {
    return this.svc.updatePreferences(u.id, b);
  }
}

@Module({ controllers: [ProfileController], providers: [ProfileService] })
export class ProfileModule {}
